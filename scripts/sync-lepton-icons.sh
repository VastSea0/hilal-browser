#!/usr/bin/env bash
# scripts/sync-lepton-icons.sh
#
# Refresh hilal-icons.css and its SVGs from upstream Firefox-UI-Fix (Lepton).
# Hilal ships only Lepton's icon rules (menus, context menus, panels, library);
# the rest of Lepton is not used.
#
# Usage:
#   scripts/sync-lepton-icons.sh              # upstream master
#   scripts/sync-lepton-icons.sh v8.0.0       # tag or full commit hash

set -euo pipefail

# shellcheck source=lib.sh
. "$(dirname "$0")/lib.sh"

REF="${1:-master}"
UPSTREAM_URL="${HILAL_LEPTON_UPSTREAM:-https://github.com/black7375/Firefox-UI-Fix.git}"
WORK_DIR="${HILAL_LEPTON_WORK:-$HILAL_REPO_ROOT/.cache/firefox-ui-fix}"
THEME_DIR="$HILAL_REPO_ROOT/changes/browser/themes/shared"
DEST="$THEME_DIR/hilal-icons.css"
ICON_DIR="$THEME_DIR/icons"
SOURCE_META="$HILAL_REPO_ROOT/third_party/firefox-ui-fix/SOURCE"
JAR_PATCH="$HILAL_REPO_ROOT/changes/browser/themes/hilal-theme-integration.patch"

command -v git >/dev/null 2>&1 || die "Required command not found: git"
command -v python3 >/dev/null 2>&1 || die "Required command not found: python3"

mkdir -p "$(dirname "$WORK_DIR")"
if [ ! -d "$WORK_DIR/.git" ]; then
  log "Cloning Firefox-UI-Fix into $WORK_DIR"
  git clone --no-tags "$UPSTREAM_URL" "$WORK_DIR"
fi

# Upstream has tags that differ only in case, so fetch just the one ref.
log "Fetching $REF"
git -C "$WORK_DIR" fetch --no-tags origin "$REF"
git -C "$WORK_DIR" checkout --force --detach FETCH_HEAD
PINNED_COMMIT="$(git -C "$WORK_DIR" rev-parse HEAD)"
PINNED_DATE="$(git -C "$WORK_DIR" log -1 --format=%cs)"

# Upstream commits the compiled css/leptonChrome.css, so no Sass build is needed.
python3 - "$WORK_DIR" "$DEST" "$ICON_DIR" "$PINNED_COMMIT" <<'PY'
import pathlib
import re
import shutil
import sys

work, dest, icon_dir = map(pathlib.Path, sys.argv[1:4])
commit = sys.argv[4]
text = (work / "css/leptonChrome.css").read_text(encoding="utf-8")

start = text.index("/** Icons ***")
end = text.index("/*@ DEPRECATED", start)
section = text[start:end].rstrip() + "\n"
section = section.replace("../icons/", "chrome://browser/skin/icons/")

header = f"""/* Icon rules from Firefox-UI-Fix (Lepton), upstream commit {commit[:12]}.
 * Upstream: https://github.com/black7375/Firefox-UI-Fix
 * License: MPL 2.0, see third_party/firefox-ui-fix/LICENSE
 * Generated by scripts/sync-lepton-icons.sh; do not edit by hand.
 */
@namespace xul url("http://www.mozilla.org/keymaster/gatekeeper/there.is.only.xul");
@namespace html url("http://www.w3.org/1999/xhtml");
"""
dest.write_text(header + section, encoding="utf-8")

used = sorted(set(re.findall(r"chrome://browser/skin/icons/([^\")]+)", section)))
for old in icon_dir.glob("*.svg"):
    old.unlink()
missing = []
for name in used:
    src = work / "icons" / name
    if src.exists():
        shutil.copy2(src, icon_dir / name)
    else:
        missing.append(name)
for name in missing:
    print(f"warning: upstream references icons/{name} but does not ship it", file=sys.stderr)
PY

log "Checking jar.inc.mn entries in $(basename "$JAR_PATCH")"
expected="$(cd "$ICON_DIR" && ls ./*.svg | sed 's|^\./||' | sort)"
listed="$(grep -o 'skin/classic/browser/icons/[^ ]*' "$JAR_PATCH" | sed 's|.*/||' | sort)"
if [ "$expected" != "$listed" ]; then
  warn "Icon list in jar.inc.mn no longer matches $ICON_DIR:"
  diff <(echo "$listed") <(echo "$expected") >&2 || true
  warn "Update the jar.inc.mn hunk in $JAR_PATCH."
fi

if [ -f "$SOURCE_META" ]; then
  python3 - "$SOURCE_META" "$PINNED_COMMIT" "$PINNED_DATE" <<'PY'
import pathlib
import re
import sys

path, commit, date = sys.argv[1:4]
text = pathlib.Path(path).read_text(encoding="utf-8")
text = re.sub(r"^pinned_commit=.*$", f"pinned_commit={commit}", text, flags=re.M)
text = re.sub(r"^pinned_date=.*$", f"pinned_date={date}", text, flags=re.M)
pathlib.Path(path).write_text(text, encoding="utf-8")
PY
fi

log "Wrote $DEST (pinned $PINNED_COMMIT)"
