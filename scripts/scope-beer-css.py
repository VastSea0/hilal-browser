#!/usr/bin/env python3
# Generate changes/browser/themes/shared/hilal-beer.css from beer.min.css.
#
# Beer CSS is written for web pages: it restyles html, body, label and every
# element through `*`. Loaded as is into browser.xhtml it also restyles
# Firefox's own menus and panels. This wraps its rules in @scope (.beer) so they
# only reach the shell elements that carry the "beer" class. Custom property
# definitions, @font-face and @keyframes stay global.

import re
import sys
from pathlib import Path

SHARED = Path(__file__).resolve().parent.parent / "changes/browser/themes/shared"
SOURCE = SHARED / "beer.min.css"
OUTPUT = SHARED / "hilal-beer.css"

GLOBAL_AT_RULES = ("@font-face", "@keyframes", "@-webkit-keyframes", "@import", "@charset")
TOKEN_SELECTORS = {":root", "body.light", "body.dark"}


def split_rules(css):
    """Split a stylesheet into top-level (prelude, block) pairs."""
    rules = []
    depth = 0
    start = 0
    prelude = None
    quote = None
    i = 0
    while i < len(css):
        c = css[i]
        if quote:
            if c == "\\":
                i += 1
            elif c == quote:
                quote = None
        elif c in "\"'":
            quote = c
        elif css.startswith("/*", i):
            i = css.index("*/", i) + 1
        elif c == "{":
            if depth == 0:
                prelude = css[start:i].strip()
                start = i + 1
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                rules.append((prelude, css[start:i]))
                start = i + 1
        elif c == ";" and depth == 0:
            rules.append((css[start:i].strip(), None))
            start = i + 1
        i += 1
    return rules


def declarations(block):
    """Split a declaration block on semicolons outside parentheses."""
    decls = []
    depth = 0
    start = 0
    for i, c in enumerate(block):
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        elif c == ";" and depth == 0:
            decls.append(block[start:i])
            start = i + 1
    decls.append(block[start:])
    return [d.strip() for d in decls if d.strip()]


def only_custom_properties(block):
    return all(decl.startswith("--") for decl in declarations(block))


def main():
    global_rules = []
    scoped_rules = []
    for prelude, block in split_rules(SOURCE.read_text()):
        if block is None:
            global_rules.append(prelude + ";")
            continue
        rule = f"{prelude}{{{block}}}"
        selectors = {s.strip() for s in prelude.split(",")}
        if prelude.startswith(GLOBAL_AT_RULES):
            global_rules.append(rule)
        elif selectors <= TOKEN_SELECTORS and only_custom_properties(block):
            global_rules.append(rule)
        elif prelude.startswith("@-moz-document"):
            scoped_rules.append(block)
        elif selectors <= {"html", "body"}:
            scoped_rules.append(f":scope{{{block}}}")
        else:
            scoped_rules.append(rule)

    header = (
        "/* Generated by scripts/scope-beer-css.py from beer.min.css; "
        "do not edit by hand. */\n"
    )
    OUTPUT.write_text(
        header + "".join(global_rules) + "@scope (.beer){" + "".join(scoped_rules) + "}\n"
    )
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    sys.exit(main())
