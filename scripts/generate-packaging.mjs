#!/usr/bin/env node
// Writes the package manager manifests for one desktop release from its
// SHA256SUMS: the AUR PKGBUILD, the Scoop bucket, the winget manifests, the
// Homebrew cask and the Flatpak archive hash. release.yml runs it after a
// release is published and commits the result to main, which is where the
// Scoop bucket and the Homebrew tap are read from.
//
//   node scripts/generate-packaging.mjs --tag v0.4.0-alpha.3 --sums SHA256SUMS [--date 2026-11-11] [--root .]

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const REPO = "VastSea0/hilal-browser";
const HOMEPAGE = "https://hilal-browser.vercel.app";
const SOURCE = `https://github.com/${REPO}`;
const DESCRIPTION = "Privacy-first web browser built on Firefox ESR";
const WINGET_ID = "VastSea0.Hilal";
const WINGET_SCHEMA = "1.9.0";

const args = parseArgs(process.argv.slice(2));
const tag = args.tag;
if (!/^v\d+\.\d+\.\d+(-[0-9A-Za-z.]+)?$/.test(tag ?? "")) {
  fail("--tag must look like v0.4.0 or v0.4.0-alpha.3");
}
if (!args.sums) {
  fail("--sums is required");
}
const version = tag.slice(1);
const date = args.date ?? new Date().toISOString().slice(0, 10);
const root = resolve(args.root ?? ".");
const sums = parseSums(readFileSync(args.sums, "utf8"));
const download = name => `${SOURCE}/releases/download/${tag}/${name}`;

const assets = {
  linux: `Hilal-${version}-linux-x86_64.tar.xz`,
  zip: `Hilal-${version}-win64.zip`,
  setup: `Hilal-${version}-win64-setup.exe`,
  dmg: `Hilal-Browser-${tag}-macOS.dmg`,
};
const hash = {};
for (const [key, name] of Object.entries(assets)) {
  hash[key] = sums.get(name) ?? fail(`SHA256SUMS has no entry for ${name}`);
}

writeAur();
writeScoop();
writeWinget();
writeCask();
updateFlatpakHash();

function writeAur() {
  // pacman versions cannot contain "-"; "_" keeps 0.4.0_alpha.3 older than 0.4.0.
  const pkgver = version.replaceAll("-", "_");
  const tarball = `Hilal-\${_ver}-linux-x86_64.tar.xz`;
  // The PKGBUILD downloads these from the tag, so hash them as tagged.
  const desktopHash = taggedFileHash("flatpak/io.github.VastSea0.Hilal.desktop");
  const metainfoHash = taggedFileHash("flatpak/io.github.VastSea0.Hilal.metainfo.xml");
  const pkgbuild = `# Generated by scripts/generate-packaging.mjs; edit the script, not this file.
pkgname=hilal-browser-bin
_ver=${version}
pkgver=${pkgver}
pkgrel=1
pkgdesc="${DESCRIPTION}"
arch=('x86_64')
url="${HOMEPAGE}"
license=('MPL-2.0')
depends=('gtk3' 'libxt' 'mime-types' 'dbus-glib' 'nss' 'ttf-font' 'libpulse' 'alsa-lib')
makedepends=('python')
optdepends=('libnotify: desktop notifications'
            'hunspell-en_us: spell checking'
            'xdg-desktop-portal: screen sharing and file pickers')
provides=('hilal-browser')
conflicts=('hilal-browser')
options=('!strip' '!debug')
source=("${tarball}::${SOURCE}/releases/download/v\${_ver}/${tarball}"
        "io.github.VastSea0.Hilal.desktop::https://raw.githubusercontent.com/${REPO}/v\${_ver}/flatpak/io.github.VastSea0.Hilal.desktop"
        "io.github.VastSea0.Hilal.metainfo.xml::https://raw.githubusercontent.com/${REPO}/v\${_ver}/flatpak/io.github.VastSea0.Hilal.metainfo.xml")
sha256sums=('${hash.linux}'
            '${desktopHash}'
            '${metainfoHash}')

package() {
  install -d "\${pkgdir}/opt"
  cp -a firefox "\${pkgdir}/opt/hilal-browser"

  # pacman delivers updates, so switch off the built-in updater and keep the
  # rest of Hilal's policies.
  python - "\${pkgdir}/opt/hilal-browser/distribution/policies.json" <<'EOF'
import json, sys
p = sys.argv[1]
with open(p) as f:
    d = json.load(f)
d.setdefault("policies", {})["DisableAppUpdate"] = True
d["policies"].pop("AppUpdateURL", None)
with open(p, "w") as f:
    json.dump(d, f, indent=2)
EOF

  install -d "\${pkgdir}/usr/bin"
  cat > "\${pkgdir}/usr/bin/hilal" <<'EOF'
#!/bin/sh
exec /opt/hilal-browser/firefox --name io.github.VastSea0.Hilal "$@"
EOF
  chmod 755 "\${pkgdir}/usr/bin/hilal"

  install -Dm644 io.github.VastSea0.Hilal.desktop "\${pkgdir}/usr/share/applications/io.github.VastSea0.Hilal.desktop"
  install -Dm644 io.github.VastSea0.Hilal.metainfo.xml "\${pkgdir}/usr/share/metainfo/io.github.VastSea0.Hilal.metainfo.xml"
  for size in 16 32 48 64 128; do
    install -Dm644 "firefox/browser/chrome/icons/default/default\${size}.png" \\
      "\${pkgdir}/usr/share/icons/hicolor/\${size}x\${size}/apps/io.github.VastSea0.Hilal.png"
  done
}
`;
  const srcinfo = `pkgbase = hilal-browser-bin
\tpkgdesc = ${DESCRIPTION}
\tpkgver = ${pkgver}
\tpkgrel = 1
\turl = ${HOMEPAGE}
\tarch = x86_64
\tlicense = MPL-2.0
\tmakedepends = python
\tdepends = gtk3
\tdepends = libxt
\tdepends = mime-types
\tdepends = dbus-glib
\tdepends = nss
\tdepends = ttf-font
\tdepends = libpulse
\tdepends = alsa-lib
\toptdepends = libnotify: desktop notifications
\toptdepends = hunspell-en_us: spell checking
\toptdepends = xdg-desktop-portal: screen sharing and file pickers
\tprovides = hilal-browser
\tconflicts = hilal-browser
\toptions = !strip
\toptions = !debug
\tsource = ${assets.linux}::${download(assets.linux)}
\tsource = io.github.VastSea0.Hilal.desktop::https://raw.githubusercontent.com/${REPO}/${tag}/flatpak/io.github.VastSea0.Hilal.desktop
\tsource = io.github.VastSea0.Hilal.metainfo.xml::https://raw.githubusercontent.com/${REPO}/${tag}/flatpak/io.github.VastSea0.Hilal.metainfo.xml
\tsha256sums = ${hash.linux}
\tsha256sums = ${desktopHash}
\tsha256sums = ${metainfoHash}

pkgname = hilal-browser-bin
`;
  write("packaging/aur/hilal-browser-bin/PKGBUILD", pkgbuild);
  write("packaging/aur/hilal-browser-bin/.SRCINFO", srcinfo);
}

function writeScoop() {
  // Scoop delivers updates, so switch off the built-in updater. WriteAllText
  // writes UTF-8 without a byte order mark, which Firefox's JSON reader needs.
  const disableUpdates = [
    "$p = \"$dir\\distribution\\policies.json\"",
    "$j = Get-Content -Raw $p | ConvertFrom-Json",
    "$j.policies | Add-Member -NotePropertyName DisableAppUpdate -NotePropertyValue $true -Force",
    "$j.policies.PSObject.Properties.Remove('AppUpdateURL')",
    "[IO.File]::WriteAllText($p, ($j | ConvertTo-Json -Depth 32))",
  ];
  const manifest = {
    version,
    description: DESCRIPTION,
    homepage: HOMEPAGE,
    license: "MPL-2.0",
    architecture: {
      "64bit": {
        url: download(assets.zip),
        hash: hash.zip,
        extract_dir: "firefox",
      },
    },
    bin: [["firefox.exe", "hilal"]],
    shortcuts: [["firefox.exe", "Hilal Browser"]],
    post_install: disableUpdates,
    checkver: { github: SOURCE },
    autoupdate: {
      architecture: {
        "64bit": {
          url: `${SOURCE}/releases/download/v$version/Hilal-$version-win64.zip`,
        },
      },
      hash: { url: `${SOURCE}/releases/download/v$version/SHA256SUMS` },
    },
  };
  write("bucket/hilal-browser.json", JSON.stringify(manifest, null, 2) + "\n");
}

function writeWinget() {
  const base = "packaging/winget";
  rmSync(join(root, base), { recursive: true, force: true });
  const dir = `${base}/manifests/v/VastSea0/Hilal/${version}`;
  const header = type =>
    `# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.${WINGET_SCHEMA}.schema.json\n` +
    `# Generated by scripts/generate-packaging.mjs; edit the script, not this file.\n\n`;
  const footer = type => `ManifestType: ${type}\nManifestVersion: ${WINGET_SCHEMA}\n`;

  write(
    `${dir}/${WINGET_ID}.yaml`,
    header("version") +
      `PackageIdentifier: ${WINGET_ID}\nPackageVersion: ${version}\nDefaultLocale: en-US\n` +
      footer("version")
  );
  write(
    `${dir}/${WINGET_ID}.installer.yaml`,
    header("installer") +
      `PackageIdentifier: ${WINGET_ID}
PackageVersion: ${version}
InstallerType: nullsoft
Scope: machine
UpgradeBehavior: install
ReleaseDate: ${date}
Installers:
- Architecture: x64
  InstallerUrl: ${download(assets.setup)}
  InstallerSha256: ${hash.setup.toUpperCase()}
` +
      footer("installer")
  );
  write(
    `${dir}/${WINGET_ID}.locale.en-US.yaml`,
    header("defaultLocale") +
      `PackageIdentifier: ${WINGET_ID}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: Hilal Browser contributors
PublisherUrl: ${SOURCE}
PublisherSupportUrl: ${SOURCE}/issues
PrivacyUrl: ${HOMEPAGE}/privacy.html
PackageName: Hilal Browser
PackageUrl: ${HOMEPAGE}
License: MPL-2.0
LicenseUrl: ${SOURCE}/blob/main/LICENSE
ShortDescription: ${DESCRIPTION}
Description: Hilal is a free and open source browser built on Firefox ESR, with vertical tabs, workspaces, Boosts and a Material 3 Expressive design.
Moniker: hilal
Tags:
- browser
- firefox
- privacy
- web-browser
ReleaseNotesUrl: ${SOURCE}/releases/tag/${tag}
` +
      footer("defaultLocale")
  );
}

function writeCask() {
  const cask = `# Generated by scripts/generate-packaging.mjs; edit the script, not this file.
cask "hilal-browser" do
  version "${version}"
  sha256 "${hash.dmg}"

  url "${SOURCE}/releases/download/v#{version}/Hilal-Browser-v#{version}-macOS.dmg"
  name "Hilal Browser"
  desc "${DESCRIPTION}"
  homepage "${HOMEPAGE}"

  livecheck do
    url :url
    strategy :github_latest
  end

  auto_updates true
  depends_on arch: :arm64

  app "Hilal Browser.app"

  # Hilal is ad-hoc signed because it has no paid Apple Developer ID, so
  # Gatekeeper would refuse to open a quarantined copy.
  postflight do
    system_command "/usr/bin/xattr",
                   args: ["-dr", "com.apple.quarantine", "#{appdir}/Hilal Browser.app"]
  end

  zap trash: [
    "~/Library/Application Support/Hilal",
    "~/Library/Caches/Hilal",
  ]
end
`;
  write("Casks/hilal-browser.rb", cask);
}

function updateFlatpakHash() {
  const file = join(root, "io.github.VastSea0.Hilal.yml");
  const text = readFileSync(file, "utf8");
  const block = /(# HILAL_ARCHIVE_BEGIN[\s\S]*?url: )(\S+)(\s+sha256: )([0-9a-f]{64})([\s\S]*?# HILAL_ARCHIVE_END)/;
  if (!block.test(text)) {
    fail("io.github.VastSea0.Hilal.yml has no HILAL_ARCHIVE block with a url and sha256");
  }
  writeFileSync(file, text.replace(block, `$1${download(assets.linux)}$3${hash.linux}$5`));
}

function taggedFileHash(path) {
  const data = execFileSync("git", ["show", `${tag}:${path}`], { cwd: root, maxBuffer: 1 << 26 });
  return createHash("sha256").update(data).digest("hex");
}

function write(rel, content) {
  const file = join(root, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  console.log(`wrote ${rel}`);
}

function parseSums(text) {
  const map = new Map();
  for (const line of text.split("\n")) {
    const m = line.match(/^([0-9a-f]{64})\s+\*?(.+)$/);
    if (m) {
      map.set(m[2].trim(), m[1]);
    }
  }
  return map;
}

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    const m = argv[i].match(/^--([a-z]+)$/);
    if (!m || i + 1 >= argv.length) {
      fail(`unexpected argument ${argv[i]}`);
    }
    out[m[1]] = argv[++i];
  }
  return out;
}

function fail(message) {
  console.error(`generate-packaging: ${message}`);
  process.exit(1);
}
